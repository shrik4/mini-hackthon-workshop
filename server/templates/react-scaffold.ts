function generateComponentFiles(features: Feature[]): Record<string, string> {
  const files: Record<string, string> = {};
  
  features.forEach((feature, index) => {
    const componentName = feature.title.replace(/[^a-zA-Z0-9]/g, '');
    files[`src/components/${componentName}.tsx`] = `import React from 'react';

interface ${componentName}Props {
  // Add your props here
}

export default function ${componentName}(props: ${componentName}Props) {
  return (
    <div className="p-4 border rounded-lg">
      <h3 className="text-lg font-semibold mb-2">${feature.title}</h3>
      <p className="text-gray-600">${feature.description}</p>
      <div className="mt-4 text-sm text-gray-500">
        Tech Stack: ${feature.techStack}
      </div>
    </div>
  );
}`;
  });
  
  return files;
}
